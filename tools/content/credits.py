"""Builds the game's credits (data/credits.json) from the bibliography and the README, so they never drift (issue #14).

Run after changing docs/sources.md or the README's "Use of AI" / "Credits" sections:
    python tools/content/credits.py
tests/ci/credits.gd fails when a source in docs/sources.md is missing from data/credits.json.

What goes in:
- Every source entry of docs/sources.md (lines "- **ID** ..."), by section, the section "Still to add" left out.
- The README's "Use of AI" bullets (the agents and models used), its "Credits" bullets (engine, font, imagery) and
  its "Team" section: the team's line and one bullet per person (name, what they did, their links). Lines marked TODO are left out.
Markdown is reduced to plain text, with links kept as URLs so the game can make them clickable.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SOURCES = os.path.join(ROOT, "docs", "sources.md")
README = os.path.join(ROOT, "README.md")
OUT = os.path.join(ROOT, "data", "credits.json")
SKIP_SECTIONS = ("Still to add",)


def plain(md):
    """Markdown to plain text: [text](url) -> text (url); **x**, *x*, `x` -> x."""
    s = re.sub(r"\[([^\]]+)\]\((https?://[^)]+)\)", r"\1 (\2)", md)
    s = re.sub(r"\*\*([^*]+)\*\*", r"\1", s)
    s = re.sub(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])", r"\1", s)
    s = s.replace("`", "")
    return re.sub(r"\s+", " ", s).strip()


def section_title(h):
    """'NASA data used by ... (issue 19; pipeline in `tools/content/data/`)' -> 'NASA data used by ...'."""
    return plain(re.sub(r"\s*\((issue|issues)[^)]*\)\s*$", "", h)).strip()


def bullets(lines):
    """Joins markdown bullets with their indented continuation lines."""
    out = []
    for line in lines:
        if line.startswith("- "):
            out.append(line[2:].rstrip())
        elif out and line.startswith("  ") and line.strip():
            out[-1] += " " + line.strip()
        elif not line.strip() and out:
            out.append(None)
    return [b for b in out if b]


def read_sources():
    sections = []
    cur = None
    lines = open(SOURCES, encoding="utf-8").read().splitlines()
    body = []

    def flush():
        if cur and not cur["title"].startswith(SKIP_SECTIONS):
            for b in bullets(body):
                m = re.match(r"\*\*(S[-0-9a-z]+)\*\*\s*(.*)", b)
                if m:
                    cur["entries"].append({"id": m.group(1), "text": plain(m.group(2))})
            if cur["entries"]:
                sections.append(cur)

    for line in lines:
        if line.startswith("## "):
            flush()
            cur = {"title": section_title(line[3:]), "entries": []}
            body = []
        elif cur is not None:
            body.append(line)
    flush()
    return sections


def readme_section(name):
    text = open(README, encoding="utf-8").read()
    m = re.search(r"(?ms)^## " + re.escape(name) + r"\s*\n(.*?)(?=^## |\Z)", text)
    return m.group(1) if m else ""


def main():
    sections = read_sources()
    ai_text = readme_section("Use of AI")
    ai = [plain(b) for b in bullets(ai_text.splitlines()) if "TODO" not in b]
    ai_note = [plain(p) for p in re.split(r"\n\s*\n", ai_text) if p.strip() and not p.strip().startswith("-")]
    built = [plain(b) for b in bullets(readme_section("Credits").splitlines()) if "TODO" not in b]
    team_text = readme_section("Team").strip()
    team = plain(team_text.splitlines()[0]) if team_text else ""
    people = []
    for b in bullets(team_text.splitlines()):
        m = re.match(r"\*\*([^*]+)\*\*:?\s*(.*)", b)
        if not m:
            continue
        links = [{"label": l, "url": u} for l, u in re.findall(r"\[([^\]]+)\]\((https?://[^)]+)\)", m.group(2))]
        role = plain(re.sub(r"\[([^\]]+)\]\((https?://[^)]+)\)", "", m.group(2))).strip().rstrip(".") + "."
        people.append({"name": m.group(1).strip(), "role": role, "links": links})
    data = {
        "_about": "Generated by tools/content/credits.py from docs/sources.md and README.md. Do not edit by hand.",
        "team": team,
        "people": people,
        "ai": ai,
        "ai_note": ai_note,
        "built_with": built,
        "sections": sections,
        "count": sum(len(s["entries"]) for s in sections),
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("wrote", OUT, data["count"], "sources in", len(sections), "sections,", len(ai), "AI lines")


if __name__ == "__main__":
    main()
